    public void aff_A_Utilisateur(C_Utilisateur gestionUtilisateur, LinkedHashMap<Integer, M_Role> lesRoles) {
        this.gestionUtilisateur = gestionUtilisateur;
        this.lesRoles = lesRoles;
        this.setTitle("Ajout d'un bâtiments");
        this.setSize(1080, 720);
        this.setLocationRelativeTo(null);

        for (Integer uneCle : lesRoles.keySet()) {
            unRole = lesRoles.get(uneCle);
            cb_role.addItem(unRole.getNom());
        }

        setVisible(true);
    }

    private int getIdByNom(String codeNom) {
        int res = -1;
        for (M_Role role : lesRoles.values()) {
            if (role.getNom().equals(codeNom)) {
                res = role.getId();
            }
        }
        return res;
    }

