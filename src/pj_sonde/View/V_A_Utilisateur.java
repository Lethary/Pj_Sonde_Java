    private void btn_addActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_addActionPerformed
        String name, email, password, commentaire;
        int idRole;
        // Vérification des champs obligatoires
        JTextField[] champs = {ftf_name, ftf_email, ftf_password};

        for (JTextField champ : champs) {
            if (champ.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Veuillez remplir tous les champs", "Erreur", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        // Vérification des longueurs
        if (ftf_email.getText().length() > 255) {
            JOptionPane.showMessageDialog(this, "Le nom doit contenir moins de 255 caractères", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        email = ftf_email.getText();

        if (ftf_name.getText().length() > 255) {
            JOptionPane.showMessageDialog(this, "Le code doit contenir moins de 255 caractères", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        name = ftf_name.getText();

        if (ftf_password.getText().length() > 255) {
            JOptionPane.showMessageDialog(this, "Le code doit contenir moins de 255 caractères", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!(ftf_password.getText().equals(ftf_password_confirm.getText()))) {
            JOptionPane.showMessageDialog(this, "Les deux mots de passe ne correspondent pas", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        password = BCrypt.withDefaults().hashToString(12, ftf_password.getText().toCharArray());

        // Si commentaire renseigné, vérification de la longueur
        if (ta_commentaire.getText().length() > 250) {
            JOptionPane.showMessageDialog(this, "Le commentaire doit contenir moins de 250 caractères", "Erreur", JOptionPane.ERROR_MESSAGE);
            return;
        }
        commentaire = ta_commentaire.getText().isEmpty() ? null : ta_commentaire.getText(); //Soit on recupère le commentaire soit on met à null

        // Vérification si le bâtiments existe 
        try {
            if (gestionUtilisateur.utilisateurExiste(email)) {
                JOptionPane.showMessageDialog(this, "L'email est déjà utilisé", "Erreur", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (Exception ex) {
            Logger.getLogger(V_A_Utilisateur.class.getName()).log(Level.SEVERE, null, ex);
        }
        idRole = getIdByNom((String) cb_role.getSelectedItem());

        // Enregistrement en DB
        try {
            gestionUtilisateur.add_Utilisateur(name, email, password, commentaire, idRole);
            JOptionPane.showMessageDialog(this, "L'utilisateur " + name + " a bien été ajouté", "Confirmation", JOptionPane.INFORMATION_MESSAGE);
            ftf_name.setText("");
            ftf_email.setText("");
            ta_commentaire.setText("");
            setVisible(false);
        } catch (Exception ex) {
            Logger.getLogger(V_A_Utilisateur.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btn_addActionPerformed

